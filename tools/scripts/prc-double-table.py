"""Turns the table of frequent doubles and exponents in prc-rs's src/double.rs (MIT) into the C# data file
of Scene3D.Prc. Run once; the output is checked in.

  python prc-double-table.py <path to double.rs> <path to PrcDoubleTable.g.cs>
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
rows = []
pat = re.compile(r'XX!\{VT::(double|exponent),\s*(\d+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\}')
for line in open(src, encoding='utf-8'):
    m = pat.search(line)
    if m:
        rows.append((m.group(1) == 'exponent', int(m.group(2)), int(m.group(3), 16), (int(m.group(4), 16) << 32) | int(m.group(5), 16)))
assert len(rows) == 2077, len(rows)

with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated>\n')
    f.write('// The table of frequent doubles and exponents of the PRC double encoding, taken from prc-rs\n')
    f.write('// (src/double.rs, MIT, Copyright Kristof Ralovich 2025-2026; see THIRD-PARTY-NOTICES.md) by\n')
    f.write('// tools/prc-double-table.py in the 3D workspace. Do not edit.\n')
    f.write('// </auto-generated>\n\n')
    f.write('namespace Scene3D.Prc.Bits;\n\n')
    f.write('internal static partial class PrcDoubles\n{\n')
    f.write(f'    private const int TableCount = {len(rows)};\n\n')
    f.write('    /// <summary>Per entry: the code (low 22 bits), its length in bits (bits 24-28), and bit 31 set for an exponent.</summary>\n')
    f.write('    private static ReadOnlySpan<uint> TableCodes =>\n    [\n')
    for i in range(0, len(rows), 8):
        f.write('        ' + ' '.join(f'0x{(c | (n << 24) | (0x80000000 if e else 0)):08X},' for e, n, c, _ in rows[i:i + 8]) + '\n')
    f.write('    ];\n\n')
    f.write('    /// <summary>Per entry: the bits of the double the code stands for (sign and mantissa may follow in the stream).</summary>\n')
    f.write('    private static ReadOnlySpan<ulong> TableValues =>\n    [\n')
    for i in range(0, len(rows), 4):
        f.write('        ' + ' '.join(f'0x{v:016X},' for _, _, _, v in rows[i:i + 4]) + '\n')
    f.write('    ];\n}\n')
assert all(c < (1 << 22) and 1 <= n <= 22 for _, n, c, _ in rows)
print('entries', len(rows), 'max bits', max(n for _, n, _, _ in rows))
