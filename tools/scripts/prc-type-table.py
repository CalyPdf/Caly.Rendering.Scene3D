import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
start = src.index('pub enum PrcType {')
body = src[start:src.index('\n}', start)]
entries = re.findall(r'^\s*(PRC_TYPE_[A-Za-z0-9_]+)\s*=\s*([0-9]+)\s*,', body, re.M)
if len(entries) < 100:
    raise SystemExit('PrcType enum not found as expected')

out = ['''// <auto-generated>
// The entity type numbers of PRC (ISO 14739-1), as listed by prc-rs (src/constants.rs, MIT,
// Copyright Kristof Ralovich 2025-2026; see THIRD-PARTY-NOTICES.md), written by
// tools/prc-type-table.py in the 3D workspace. Do not edit.
// </auto-generated>

namespace Scene3D.Prc;

/// <summary>The number that starts each kind of PRC entity. The names are the format's own.</summary>
internal static class PrcType
{
''']
for name, value in entries:
    out.append(f'    public const uint {name} = {value};\n')
out.append('''
    /// <summary>The format's name of a type number, or the number itself for one it does not name.</summary>
    public static string NameOf(uint type) => type switch
    {
''')
seen = set()
for name, value in entries:
    if value in seen:
        continue
    seen.add(value)
    out.append(f'        {value} => "{name}",\n')
out.append('''        _ => type.ToString(System.Globalization.CultureInfo.InvariantCulture),
    };
}
''')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write(''.join(out))
print(len(entries), 'types')
